"""Mass attenuation coefficients for water and iodine.

The data table is generated by ``tools/make_material_table.py`` from the NIST
XCOM database via ``xraylib`` and committed as CSV; it is never hand-edited.
Interpolation is log-log, which is standard for attenuation data.
"""

from __future__ import annotations

import csv
import io
from functools import lru_cache
from importlib import resources

import numpy as np

MATERIALS = ("water", "iodine")
ENERGY_RANGE_KEV = (10.0, 150.0)
WATER_DENSITY_G_CM3 = 1.0


@lru_cache(maxsize=1)
def _table() -> tuple[np.ndarray, dict[str, np.ndarray]]:
    ref = resources.files("pcctvmi.data").joinpath("mass_attenuation.csv")
    text = ref.read_text(encoding="utf-8")
    energies: list[float] = []
    cols: dict[str, list[float]] = {m: [] for m in MATERIALS}
    for row in csv.DictReader(io.StringIO(text, newline="")):
        energies.append(float(row["energy_keV"]))
        for m in MATERIALS:
            cols[m].append(float(row[f"{m}_cm2_g"]))
    return np.asarray(energies, dtype=np.float64), {
        m: np.asarray(v, dtype=np.float64) for m, v in cols.items()
    }


def energies_kev() -> np.ndarray:
    """Tabulated energy grid (keV)."""
    return _table()[0].copy()


def mu_rho(material: str, energy_kev: float | np.ndarray) -> np.ndarray:
    """Mass attenuation coefficient (cm^2/g), log-log interpolated.

    Raises:
        ValueError: unknown material or energy outside the tabulated range.
    """
    if material not in MATERIALS:
        raise ValueError(f"unknown material {material!r}; choose from {MATERIALS}")
    grid, cols = _table()
    e = np.asarray(energy_kev, dtype=np.float64)
    lo, hi = float(grid[0]), float(grid[-1])  # range follows the generated table
    if e.size == 0:
        return np.empty(0, dtype=np.float64)
    if float(e.min()) < lo or float(e.max()) > hi:
        raise ValueError(f"energy {energy_kev} outside tabulated range [{lo}, {hi}] keV")
    mu = np.exp(np.interp(np.log(e), np.log(grid), np.log(cols[material])))
    return mu


def linear_attenuation(material: str, energy_kev: float | np.ndarray) -> np.ndarray:
    """Linear attenuation coefficient (1/cm) at unit material density.

    For water this uses 1.0 g/cm^3; for iodine the value is per g/cm^3, i.e.
    multiply by the local iodine density in g/cm^3.
    """
    mu_over_rho = mu_rho(material, energy_kev)
    if material == "water":
        return mu_over_rho * WATER_DENSITY_G_CM3
    return mu_over_rho
